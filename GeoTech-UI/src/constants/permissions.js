export const normalizeRole = (role) =>
  (role || "").toString().trim().replace(/\s+/g, "").toUpperCase();

export const can = (user, permission) => {
  const set = ROLE_PERMISSIONS[normalizeRole(user?.role)];
  return Boolean(set && set.has(permission));
};

export const isAdminLike = (user) =>
  ["SUPERADMIN", "ADMIN"].includes(normalizeRole(user?.role));
